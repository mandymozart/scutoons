export class TemplateParser {
    constructor() {
        this.autoGeneratedVars = ['code', 'qr', 'url', 'created_at', 'expires_at'];
    }

    /**
     * Parse template string and extract variables with types
     * @param {string} templateContent - The template content
     * @returns {Array} Array of field definitions
     */
    parseTemplate(templateContent) {
        const regex = /\{\{(\w+)(?::(\w+))?\}\}/g;
        const fields = new Map();
        let match;

        while ((match = regex.exec(templateContent)) !== null) {
            const varName = match[1];
            const varType = match[2] || 'text'; // Default to text if no type specified

            // Skip auto-generated variables
            if (this.autoGeneratedVars.includes(varName)) {
                continue;
            }

            // Avoid duplicates
            if (!fields.has(varName)) {
                fields.set(varName, {
                    id: varName,
                    label: this.formatLabel(varName),
                    type: this.mapFieldType(varType),
                    placeholder: this.getPlaceholder(varName, varType)
                });
            }
        }

        return Array.from(fields.values());
    }

    /**
     * Format variable name to readable label
     * @param {string} varName - Variable name
     * @returns {string} Formatted label
     */
    formatLabel(varName) {
        return varName
            .split('_')
            .map(word => word.charAt(0).toUpperCase() + word.slice(1))
            .join(' ');
    }

    /**
     * Map template type to HTML input type
     * @param {string} templateType - Type from template (text, number, date, textfield)
     * @returns {string} HTML input type
     */
    mapFieldType(templateType) {
        const typeMap = {
            'text': 'text',
            'number': 'number',
            'date': 'date',
            'textfield': 'textarea'
        };
        return typeMap[templateType] || 'text';
    }

    /**
     * Get placeholder text for field
     * @param {string} varName - Variable name
     * @param {string} varType - Variable type
     * @returns {string} Placeholder text
     */
    getPlaceholder(varName, varType) {
        const placeholders = {
            'receiver': 'John Doe',
            'productname': 'SCUTOONS Hoodie with QR Code',
            'edition_number': '1',
            'creators': 'Artist 1, Artist 2',
            'email': 'your@email.com'
        };

        if (placeholders[varName]) {
            return placeholders[varName];
        }

        if (varType === 'number') {
            return '0';
        }

        return '';
    }

    /**
     * Fetch and parse template from URL
     * @param {string} templateUrl - URL to template file
     * @returns {Promise<Array>} Array of field definitions
     */
    async fetchAndParseTemplate(templateUrl) {
        try {
            const response = await fetch(templateUrl);
            const content = await response.text();
            return this.parseTemplate(content);
        } catch (error) {
            console.error('Error fetching template:', error);
            return [];
        }
    }

    /**
     * Render template with data
     * @param {string} templateContent - Template markdown content
     * @param {Object} data - Data to fill in (qrData + templateData merged)
     * @returns {string} Rendered template with data filled in
     */
    renderTemplate(templateContent, data) {
        // Replace all {{variable}} and {{variable:type}} with actual data
        return templateContent.replace(/\{\{(\w+)(?::\w+)?\}\}/g, (match, varName) => {
            // Special handling for qr placeholder (will be replaced with image later)
            if (varName === 'qr') {
                return '[QR_CODE_PLACEHOLDER]';
            }
            
            // Return data value or empty string if not found
            return data[varName] !== undefined && data[varName] !== null ? data[varName] : '';
        });
    }

    /**
     * Fetch template and render with data
     * @param {string} templateUrl - URL to template file
     * @param {Object} data - Data to fill in
     * @returns {Promise<string>} Rendered template
     */
    async fetchAndRenderTemplate(templateUrl, data) {
        try {
            const response = await fetch(templateUrl);
            const content = await response.text();
            return this.renderTemplate(content, data);
        } catch (error) {
            console.error('Error fetching/rendering template:', error);
            return '';
        }
    }
}
