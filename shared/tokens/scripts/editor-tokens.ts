// editor.css from deck-kit's editor tokens (deck/kit/src/base/tokens.rs): the web tools take the deck's look, so its
// values are read from the Rust source, never copied by hand.
//   node --experimental-transform-types --no-warnings scripts/editor-tokens.ts           writes editor.css
//   node --experimental-transform-types --no-warnings scripts/editor-tokens.ts --check   fails when editor.css is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export type Rgba = [number, number, number, number];

export interface Look {
	colors: Record<string, Rgba>;
	panelOpacity: number;
	inkRing: boolean;
}

export interface EditorTokens {
	day: Look;
	night: Look;
	/** the sizes in rem (Rems::default) */
	rems: Record<string, number>;
	/** 1rem in px at 100 % */
	base: number;
	/** the labels' letter spacing, in em */
	spacing: number;
	/** a region's edge, px */
	edge: number;
}

const kebab = (s: string) => s.replace(/_/g, '-');

/** the body of `fn <name>(…) -> … {` up to its closing brace at the same indent */
function body(rs: string, signature: RegExp): string {
	const m = signature.exec(rs);
	if (!m) throw new Error(`tokens.rs: ${signature} not found`);
	const start = m.index + m[0].length;
	const indent = /\n([ \t]*)[^\n]*$/.exec(rs.slice(0, m.index + m[0].length))?.[1] ?? '';
	const end = rs.indexOf(`\n${indent}}`, start);
	if (end < 0) throw new Error(`tokens.rs: ${signature} has no end`);
	return rs.slice(start, end);
}

function look(src: string, name: string): Look {
	const colors: Record<string, Rgba> = {};
	let panelOpacity = NaN;
	let inkRing: boolean | undefined;
	for (const line of src.split('\n')) {
		const field = /^\s*([a-z_]+):\s*(.+?),?\s*$/.exec(line);
		if (!field) continue;
		const [, key, value] = field;
		const hex = /^rgb\(0x([0-9a-f]{6})\)$/i.exec(value);
		const arr = /^\[\s*([\d.]+),\s*([\d.]+),\s*([\d.]+),\s*([\d.]+)\s*\]$/.exec(value);
		if (hex) {
			const v = parseInt(hex[1], 16);
			colors[key] = [(v >> 16) & 255, (v >> 8) & 255, v & 255, 1];
		} else if (arr) {
			const [r, g, b, a] = arr.slice(1).map(Number);
			colors[key] = [Math.round(r * 255), Math.round(g * 255), Math.round(b * 255), a];
		} else if (key === 'panel_opacity') panelOpacity = Number(value);
		else if (key === 'ink_ring') inkRing = value === 'true';
	}
	if (!Object.keys(colors).length || Number.isNaN(panelOpacity) || inkRing === undefined) {
		throw new Error(`tokens.rs: Colors::${name}() is incomplete`);
	}
	return { colors, panelOpacity, inkRing };
}

export function parse(rs: string): EditorTokens {
	const day = look(body(rs, /pub fn day\(\) -> Colors \{/), 'day');
	const night = look(body(rs, /pub fn night\(\) -> Colors \{/), 'night');
	const rems: Record<string, number> = {};
	for (const [, k, v] of body(rs, /fn default\(\) -> Rems \{/).matchAll(/([a-z_]+):\s*([\d.]+),/g)) rems[k] = Number(v);
	const base = Number(/pub const BASE: f32 = ([\d.]+);/.exec(rs)?.[1]);
	const at = body(rs, /pub fn at\(&self, base: f32\) -> Sizes \{/);
	const spacing = Number(/spacing:\s*([\d.]+)/.exec(at)?.[1]);
	const edge = Number(/edge:\s*([\d.]+)/.exec(at)?.[1]);
	if (!Object.keys(rems).length || !base || !spacing || !edge) throw new Error('tokens.rs: the sizes are incomplete');
	return { day, night, rems, base, spacing, edge };
}

const hex2 = (n: number) => n.toString(16).padStart(2, '0');
const num = (n: number) => String(Number(n.toFixed(4)));
const colour = ([r, g, b, a]: Rgba) => (a === 1 ? `#${hex2(r)}${hex2(g)}${hex2(b)}` : `rgb(${r} ${g} ${b} / ${num(a)})`);

function lookCss(l: Look): string[] {
	const [r, g, b] = l.colors.surface;
	const surface = colour(l.colors.surface);
	return [
		...Object.entries(l.colors).map(([k, c]) => `\t--editor-${kebab(k)}: ${colour(c)};`),
		`\t--editor-panel-opacity: ${num(l.panelOpacity)};`,
		`\t/* a floating panel's see-through ground (the surface at the panel opacity, no blur) */`,
		`\t--editor-panel-ground: rgb(${r} ${g} ${b} / ${num(l.panelOpacity)});`,
		`\t/* the ink ring: text and icons on a panel take its ground's colour as an outline (deck-kit DrawList::halo) */`,
		`\t--editor-halo: ${l.inkRing ? `0 0 2px ${surface}, 0 0 2px ${surface}, 0 0 3px ${surface}` : 'none'};`,
	];
}

export function render(t: EditorTokens): string {
	return [
		'/*',
		' * @scutoons/tokens: the editor style (deck-kit\'s editor tokens) – GENERATED by scripts/editor-tokens.ts from',
		' * deck/kit/src/base/tokens.rs, do not edit. Night is the default; `data-theme="day"` on <html> or a tool root is the',
		' * day variant (`data-theme="night"` turns it back for a part). Used by tools.css (`sc-tool`).',
		' */',
		":root,\n[data-theme='night'] {",
		...lookCss(t.night),
		'}',
		'',
		"[data-theme='day'] {",
		...lookCss(t.day),
		'}',
		'',
		':root {',
		`\t/* 1rem of an editor page (deck-kit BASE); every size below is a multiple of it */`,
		`\t--editor-base: ${num(t.base)}px;`,
		...Object.entries(t.rems).map(([k, v]) => `\t--editor-${kebab(k)}: ${num(v)}rem;`),
		`\t/* the small uppercase labels' letter spacing */`,
		`\t--editor-label-spacing: ${num(t.spacing)}em;`,
		`\t/* a line or a region's edge */`,
		`\t--editor-edge: ${num(t.edge)}px;`,
		`\t/* text, labels and titles: ABC Areal where it loads (the CDN), Noto Sans stands in – deck-kit's fonts.rs */`,
		`\t--editor-sans: 'ABC Areal', 'Noto Sans', system-ui, sans-serif;`,
		'}',
		'',
	].join('\n');
}

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = join(here, '../../../deck/kit/src/base/tokens.rs');
export const TARGET = join(here, '../editor.css');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const css = render(parse(readFileSync(SOURCE, 'utf8')));
	if (process.argv.includes('--check')) {
		if (readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n') !== css) {
			console.error('shared/tokens/editor.css is out of date with deck/kit/src/base/tokens.rs: npm run editor-tokens -w @scutoons/tokens');
			process.exit(1);
		}
		console.log('@scutoons/tokens: editor.css matches deck-kit – ok');
	} else {
		writeFileSync(TARGET, css);
		console.log('wrote shared/tokens/editor.css');
	}
}
