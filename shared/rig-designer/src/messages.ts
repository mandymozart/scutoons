export type DesignerMessageKey = keyof (typeof DESIGNER_MESSAGES)['en'];
type Params = Record<string, string | number | null | undefined>;

/** one text in the app's locale, `{name}` filled from params; an unknown key shows as itself */
export function designerMessage(key: string, params: Params = {}): string {
	const table: Record<string, string> = designerLocale() === 'de' ? DESIGNER_MESSAGES.de : DESIGNER_MESSAGES.en;
	const fallback: Record<string, string> = DESIGNER_MESSAGES.en;
	return (table[key] ?? fallback[key] ?? key).replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}

/** the messages as functions, like the apps' paraglide `m` */
export const m = new Proxy({} as Record<DesignerMessageKey, (params?: Params) => string>, {
	get: (_target, key: string) => (params?: Params) => designerMessage(key, params)
});
