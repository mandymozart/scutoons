export type CatalogMessageKey = keyof (typeof CATALOG_MESSAGES)['en'];
type Params = Record<string, string | number | null | undefined>;

/** one text in the app's locale, `{name}` filled from params */
export function catalogMessage(key: CatalogMessageKey, params: Params = {}): string {
	const table: Record<string, string> = catalogLocale() === 'de' ? CATALOG_MESSAGES.de : CATALOG_MESSAGES.en;
	return (table[key] ?? CATALOG_MESSAGES.en[key] ?? key).replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}

/** the messages as functions, like the apps' paraglide `m` */
export const m = new Proxy({} as Record<CatalogMessageKey, (params?: Params) => string>, {
	get: (_target, key: string) => (params?: Params) => catalogMessage(key as CatalogMessageKey, params)
});
