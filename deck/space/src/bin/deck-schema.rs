//! deck-schema – everything generated from the kind catalog and the documents' types (#315, ENGINE-REFACTOR-PLAN §2.4):
//!
//!   server/src/Domain/Rigs/kinds.json     the explanatory catalog: every built-in kind, its ports and parameters with docs
//!   server/src/Domain/Rigs/NodeKinds.php  the validator's kinds / ports (until #313 retires it)
//!   deck/catalog/schema.json              JSON Schema (draft 2020-12) of `Catalog` and the rig `Bundle` (rig, instruments, presets)
//!   shared/live/src/catalog.ts            the same as TypeScript types
//!
//! `cargo run -p deck-space --features schema --bin deck-schema` writes them; `-- --check` only compares (exit 1 when a
//! file is stale – the deck:ci step). The protocol stays schema-first (deck/protocol/generate.ts); the kinds are Rust-first.
use deck_catalog::{catalog, Domain, PortType, Scope};
use deck_space::rig::bundle::Bundle;
use serde_json::{Map, Value};
use std::fmt::Write as _;
use std::path::PathBuf;

const HEADER: &str = "GENERATED by `cargo run -p deck-space --features schema --bin deck-schema` from deck/catalog (the kind catalog) – do not edit.";

fn main() {
    let check = std::env::args().any(|a| a == "--check");
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let cat = catalog();
    // the explanatory catalog explains everything: a kind, port or parameter without a doc string is a defect
    let undocumented: Vec<String> = cat
        .kinds
        .iter()
        .flat_map(|d| {
            let k = (d.doc.is_empty()).then(|| d.name.to_string());
            let p = d.ports.iter().filter(|p| p.doc.is_empty()).map(|p| format!("{}.{}", d.name, p.name));
            let q = d.params.iter().filter(|p| p.doc.is_empty()).map(|p| format!("{}.{} (param)", d.name, p.name));
            k.into_iter().chain(p).chain(q).collect::<Vec<_>>()
        })
        .collect();
    assert!(undocumented.is_empty(), "no doc string: {}", undocumented.join(", "));

    let defs = definitions();
    let mut files: Vec<(&str, String)> = Vec::new();
    files.push(("server/src/Domain/Rigs/kinds.json", format!("{}\n", serde_json::to_string_pretty(&cat).unwrap())));
    files.push(("server/src/Domain/Rigs/NodeKinds.php", node_kinds_php(&cat)));
    let schema = serde_json::json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "deck catalog and documents",
        "description": HEADER,
        "$defs": Value::Object(defs.clone()),
    });
    files.push(("deck/catalog/schema.json", format!("{}\n", serde_json::to_string_pretty(&schema).unwrap())));
    files.push(("shared/live/src/catalog.ts", typescript(&defs)));

    let mut stale = Vec::new();
    for (path, text) in &files {
        let full = root.join(path);
        let on_disk = std::fs::read_to_string(&full).unwrap_or_default().replace('\r', "");
        if on_disk == *text {
            continue;
        }
        if check {
            stale.push(*path);
        } else {
            std::fs::write(&full, text).unwrap_or_else(|e| panic!("{}: {e}", full.display()));
            println!("wrote {path}");
        }
    }
    if !stale.is_empty() {
        eprintln!("stale: {}\nrun: cargo run -p deck-space --features schema --bin deck-schema (in deck/)", stale.join(", "));
        std::process::exit(1);
    }
    if check {
        println!("deck-schema: {} generated files current", files.len());
    }
}

/// the `$defs` of `Catalog` and `Bundle` (rig + instruments + presets), draft 2020-12
fn definitions() -> Map<String, Value> {
    let mut g = schemars::generate::SchemaSettings::draft2020_12().into_generator();
    g.subschema_for::<deck_catalog::Catalog>();
    g.subschema_for::<Bundle>();
    g.take_definitions(true)
}

fn php_ty(t: PortType) -> &'static str {
    match t {
        PortType::Audio | PortType::Cv => "audio",
        PortType::Control | PortType::Event => "control",
        PortType::Video => "video",
    }
}

/// the validator's file: the kinds a graph may use, with domain and typed ports (RigValidator mirrors graph.rs's checks)
fn node_kinds_php(cat: &deck_catalog::Catalog) -> String {
    let ports = |d: &deck_catalog::Descriptor, dir: deck_catalog::Dir| {
        d.ports.iter().filter(|p| p.dir == dir).map(|p| format!("'{}' => '{}'", p.name, php_ty(p.ty))).collect::<Vec<_>>().join(", ")
    };
    let mut kinds = String::new();
    let mut scene_only = Vec::new();
    for d in cat.kinds.iter().filter(|d| d.scope == Scope::Graph) {
        let domain = match d.domain {
            Domain::Audio => "audio",
            Domain::Control => "control",
            Domain::Video => "video",
        };
        let _ = writeln!(
            kinds,
            "        '{}' => ['domain' => '{domain}', 'inputs' => [{}], 'outputs' => [{}]],",
            d.name,
            ports(d, deck_catalog::Dir::In),
            ports(d, deck_catalog::Dir::Out)
        );
        if d.scene_only {
            scene_only.push(format!("'{}'", d.name));
        }
    }
    format!(
        "<?php\ndeclare(strict_types=1);\n\nnamespace Scutoons\\Domain\\Rigs;\n\n/**\n * GENERATED from deck/catalog (the kind catalog) – do not edit: `cargo run -p deck-space --features schema --bin deck-schema`\n * writes it (deck:ci fails when it is stale). The node kinds an instrument's graph may use (RigValidator mirrors\n * graph.rs's checks with them): kind → its domain (audio · control · video – a control link into or out of an audio\n * node does not order, graph.rs `Link::orders`) and its input / output ports with their types. kinds.json beside it\n * is the full, explained catalog; until #313 retires the validator this file is its small projection.\n */\nfinal class NodeKinds\n{{\n    public const KINDS = [\n{kinds}    ];\n    /** kinds a scene owns once (the catalog's `scene_only`): never inside an instrument */\n    public const SCENE_ONLY = [{}];\n}}\n",
        scene_only.join(", ")
    )
}

// ---- TypeScript from the JSON Schema: the subset schemars writes for these types; anything else panics (like protocol/generate.ts)

fn typescript(defs: &Map<String, Value>) -> String {
    let mut out = format!("// {HEADER}\n// The kind catalog (`Catalog`, `Descriptor`, …) and the rig bundle documents (`Bundle`, `Instrument`, `Preset`, …).\n\n");
    for (name, schema) in defs {
        let doc = schema.get("description").and_then(Value::as_str);
        if let Some(d) = doc {
            let _ = writeln!(out, "/** {} */", d.replace("*/", "* /").replace('\n', " "));
        }
        let _ = writeln!(out, "export type {name} = {};\n", ts(schema, name));
    }
    out
}

fn lit(v: &Value) -> String {
    serde_json::to_string(v).unwrap()
}

fn ts(s: &Value, ctx: &str) -> String {
    if let Some(b) = s.as_bool() {
        assert!(b, "{ctx}: schema `false`");
        return "unknown".into();
    }
    let o = s.as_object().unwrap_or_else(|| panic!("{ctx}: schema is not an object"));
    if let Some(r) = o.get("$ref") {
        let r = r.as_str().unwrap();
        return r.strip_prefix("#/$defs/").unwrap_or_else(|| panic!("{ctx}: unsupported $ref {r}")).to_string();
    }
    if let Some(c) = o.get("const") {
        return lit(c);
    }
    if let Some(e) = o.get("enum") {
        return e.as_array().unwrap().iter().map(lit).collect::<Vec<_>>().join(" | ");
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(list) = o.get(key) {
            let parts: Vec<String> = list.as_array().unwrap().iter().map(|x| ts(x, ctx)).collect();
            return parts.join(" | ");
        }
    }
    if let Some(all) = o.get("allOf") {
        let parts: Vec<String> = all.as_array().unwrap().iter().map(|x| ts(x, ctx)).collect();
        return parts.join(" & ");
    }
    match o.get("type") {
        Some(Value::Array(types)) => types.iter().map(|t| ts_type(t.as_str().unwrap(), o, ctx)).collect::<Vec<_>>().join(" | "),
        Some(Value::String(t)) => ts_type(t, o, ctx),
        None if o.is_empty() => "unknown".into(),
        _ => panic!("{ctx}: unsupported schema {s}"),
    }
}

fn ts_type(t: &str, o: &Map<String, Value>, ctx: &str) -> String {
    match t {
        "string" => "string".into(),
        "integer" | "number" => "number".into(),
        "boolean" => "boolean".into(),
        "null" => "null".into(),
        "array" => {
            if let Some(items) = o.get("prefixItems") {
                let parts: Vec<String> = items.as_array().unwrap().iter().map(|x| ts(x, ctx)).collect();
                format!("[{}]", parts.join(", "))
            } else {
                let item = ts(o.get("items").unwrap_or_else(|| panic!("{ctx}: array without items")), ctx);
                if item.contains(' ') { format!("({item})[]") } else { format!("{item}[]") }
            }
        }
        "object" => {
            let props = o.get("properties").and_then(Value::as_object);
            let extra = o.get("additionalProperties").filter(|v| v.as_bool() != Some(false));
            match (props, extra) {
                (None, Some(e)) => format!("{{ [key: string]: {} }}", ts(e, ctx)),
                (None, None) => "Record<string, unknown>".into(),
                (Some(p), extra) => {
                    let required: Vec<&str> = o.get("required").and_then(Value::as_array).map(|r| r.iter().filter_map(Value::as_str).collect()).unwrap_or_default();
                    let mut s = String::from("{\n");
                    for (k, v) in p {
                        if let Some(d) = v.get("description").and_then(Value::as_str) {
                            let _ = writeln!(s, "\t/** {} */", d.replace("*/", "* /").replace('\n', " "));
                        }
                        let opt = if required.contains(&k.as_str()) { "" } else { "?" };
                        let key = if k.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') { k.clone() } else { lit(&Value::String(k.clone())) };
                        let _ = writeln!(s, "\t{key}{opt}: {};", ts(v, ctx));
                    }
                    if let Some(e) = extra {
                        let _ = writeln!(s, "\t[key: string]: {};", ts(e, ctx));
                    }
                    s.push('}');
                    s
                }
            }
        }
        other => panic!("{ctx}: unsupported type {other}"),
    }
}
