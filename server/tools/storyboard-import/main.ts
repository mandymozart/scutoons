// Writes the storyboard import migration from the scene files (#120; the logic and its tests: import-sql.ts).
//   node --experimental-transform-types --no-warnings server/tools/storyboard-import/main.ts [--check]
// --check: exit 1 when the committed migration differs from what the files give (nothing written).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chapterDoc, chapterOfFolder, migrationSql, type ChapterStoryboard } from './import-sql.ts';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const MIGRATION = '2026-10-20-storyboard-import';
const CREATED_AT = '2026-10-20 00:00:00';
const out = join(repo, 'server/migrations/mysql', `${MIGRATION}.mysql.sql`);
const HEADER = `-- The storyboards into the content store (#120, agents/research/STUDIO-IN-CREATOR.md §2.2): the scene files
-- storyboards/<toon>/s<season>c<chapter>/scene-*.json become one published version of storyboard:<toon>:<chapter> each
-- ({ storyboard: 2, toon, chapter, scenes } – the files' content as it is, scenes by source.scene; creator only,
-- EntityKey::CREATOR_ONLY_KINDS). GENERATED by server/tools/storyboard-import/main.ts – don't edit, run it again.
-- Idempotent: a chapter whose storyboard exists keeps it; nothing happens where the toon doesn't exist (test database).
-- Check first (0 rows before the first run):
--   SELECT entity_key, COUNT(*) FROM entity_versions WHERE kind = 'storyboard' GROUP BY entity_key;
`;

const root = join(repo, 'storyboards');
const docs: ChapterStoryboard[] = [];
for (const toon of readdirSync(root, { withFileTypes: true })) {
	if (!toon.isDirectory() || !/^[a-z0-9_-]+$/.test(toon.name) || toon.name === 'style' || toon.name === 'dataset') continue;
	for (const folder of readdirSync(join(root, toon.name), { withFileTypes: true })) {
		const chapter = folder.isDirectory() ? chapterOfFolder(folder.name) : null;
		if (chapter === null) continue;
		const dir = join(root, toon.name, folder.name);
		const files = readdirSync(dir)
			.filter((f) => /^scene-.+\.json$/.test(f))
			.map((f) => ({ path: `storyboards/${toon.name}/${folder.name}/${f}`, content: JSON.parse(readFileSync(join(dir, f), 'utf8')) }));
		if (files.length) docs.push(chapterDoc(toon.name, chapter, files));
	}
}

const sql = migrationSql(docs, MIGRATION, CREATED_AT, HEADER);
if (process.argv.includes('--check')) {
	const same = existsSync(out) && readFileSync(out, 'utf8') === sql;
	console.log(same ? `${MIGRATION}: up to date` : `${MIGRATION}: differs from the scene files`);
	process.exit(same ? 0 : 1);
}
writeFileSync(out, sql);
for (const d of docs) console.log(`storyboard:${d.toon}:${d.chapter}  ${d.scenes.length} scenes  ${JSON.stringify(d).length} bytes`);
console.log(`→ ${out}`);
