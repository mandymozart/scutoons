// qr's copy of @scutoons/tokens (agents/PLATFORM.md: "the server's public pages get a built copy"). qr is plain PHP
// without a build step, so the copy is generated here and committed:
//   public/assets/tokens/scutoons-tokens.css   tokens.css + the IBM Plex Mono @font-face rules of fonts.css + base.css
//   public/assets/tokens/fonts/                the Plex Mono woff2 files it references + the OFL licence
// Never edit the copy by hand: change shared/tokens and run this again.
//
//   node qr/bin/sync-tokens.mjs            write the copy
//   node qr/bin/sync-tokens.mjs --check    exit 1 when the copy differs from shared/tokens (npm run check, qr.yml)
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const qr = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = join(qr, '../shared/tokens');
const out = join(qr, 'public/assets/tokens');
const check = process.argv.includes('--check');
const read = (file) => readFileSync(join(tokens, file), 'utf8').replace(/\r\n/g, '\n');

// the Plex Mono faces only (qr has no lettering); the url()s stay relative: ./fonts/<file>
const faces = [];
const files = new Set(['IBMPlexMono-OFL.txt']);
for (const m of read('fonts.css').matchAll(/(\/\*[^*]*\*\/\s*)?@font-face\s*\{[^}]*\}/g)) {
	if (!/font-family:\s*'IBM Plex Mono'/.test(m[0])) continue;
	faces.push(m[0].trim());
	for (const [, url] of m[0].matchAll(/url\(\.\/fonts\/([^)]+)\)/g)) files.add(url);
}
if (!faces.length) throw new Error('no IBM Plex Mono @font-face in shared/tokens/fonts.css');

const css = [
	'/* GENERATED by qr/bin/sync-tokens.mjs from @scutoons/tokens (shared/tokens) – do not edit, run the script. */',
	read('tokens.css').trim(),
	'/* fonts.css: IBM Plex Mono (SIL OFL 1.1, ./fonts/IBMPlexMono-OFL.txt) */',
	faces.join('\n'),
	read('base.css').trim(),
	''
].join('\n\n');

const wanted = new Map([['scutoons-tokens.css', Buffer.from(css)]]);
for (const file of files) wanted.set(`fonts/${file}`, readFileSync(join(tokens, 'fonts', file)));

const present = (dir, prefix = '') => existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? present(join(dir, e.name), `${prefix}${e.name}/`) : [`${prefix}${e.name}`]) : [];
// text files compare without CR (a checkout with core.autocrlf=true writes CRLF)
const same = (file, a, b) => /\.(css|txt)$/.test(file) ? a.toString('utf8').replace(/\r\n/g, '\n') === b.toString('utf8').replace(/\r\n/g, '\n') : a.equals(b);
const stale = [];
for (const [file, content] of wanted) {
	const path = join(out, file);
	if (!existsSync(path) || !same(file, readFileSync(path), content)) stale.push(`${existsSync(path) ? 'changed' : 'missing'}: ${file}`);
}
for (const file of present(out)) if (!wanted.has(file)) stale.push(`extra: ${file}`);

if (check) {
	if (stale.length) {
		console.error(`qr/${relative(qr, out).replace(/\\/g, '/')} is out of date with shared/tokens – run: node qr/bin/sync-tokens.mjs\n  ${stale.join('\n  ')}`);
		process.exit(1);
	}
	console.log(`qr tokens copy: ${wanted.size} files in sync with shared/tokens – ok`);
} else {
	rmSync(out, { recursive: true, force: true });
	for (const [file, content] of wanted) {
		mkdirSync(dirname(join(out, file)), { recursive: true });
		writeFileSync(join(out, file), content);
	}
	console.log(`qr tokens copy: wrote ${wanted.size} files to qr/${relative(qr, out).replace(/\\/g, '/')}${stale.length ? ` (${stale.length} changed)` : ' (unchanged)'}`);
}
