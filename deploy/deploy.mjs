#!/usr/bin/env node
/**
 * Builds, stages and describes the deploy of one app from deploy/targets.json – the single source of truth for where
 * each app goes (agents/PLATFORM.md "Hosting layout & deployment"; docs: deploy/README.md).
 *
 *   node deploy/deploy.mjs <app|all> [--dry-run] [--skip-build] [--github] [--list=all|summary]
 *
 * 1. build     the target's `build` command (npm apps: in the repo, output = `output`; `stageFirst` apps (PHP): in the
 *              staging folder after copying, e.g. composer install --no-dev)
 * 2. stage     copies the files matching include/exclude into .deploy/<app>/ – exactly what gets uploaded
 * 3. version   writes version.json (app, version, git sha, built_at, shared package versions) at `version`
 * 4. generate  writes generated files (config.php) from environment variables; `${VAR}` unset/empty → key left out
 * 5. plan      prints every file → <protocol>://<remote><path> and the paths the deploy never touches (`protect`)
 * --github writes the plan as step outputs (protocol, local_dir, server_dir, exclude) for .github/actions/deploy,
 * which does the upload (FTP: SamKirkland/FTP-Deploy-Action). Uploading is never done by this script.
 * --dry-run: secrets in generated files are masked in the listing; with --github the action skips the upload.
 */
import { execSync } from 'node:child_process';
import { appendFileSync, cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { repoRoot, writeVersion } from './version.mjs';

const config = JSON.parse(readFileSync(join(repoRoot, 'deploy', 'targets.json'), 'utf8'));
const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const option = (name, fallback) => args.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3) ?? fallback;
const dryRun = flag('dry-run');
const skipBuild = flag('skip-build');
const github = flag('github');
const list = option('list', 'all');
const requested = args.find((a) => !a.startsWith('--'));

if (!requested || (requested !== 'all' && !config.targets[requested])) {
	console.error(`usage: node deploy/deploy.mjs <${[...Object.keys(config.targets), 'all'].join('|')}> [--dry-run] [--skip-build] [--github] [--setup]`);
	process.exit(2);
}

// --setup: what the CI job must install before building this target (npm=true|false, php=true|false, wasm=true|false)
if (flag('setup')) {
	const setup = config.targets[requested]?.setup ?? [];
	console.log(`npm=${setup.includes('npm')}\nphp=${setup.includes('php')}\nwasm=${setup.includes('wasm')}`);
	process.exit(0);
}

// CI: the workflow passes all secrets and variables of the environment as JSON (toJSON(secrets) / toJSON(vars)), so
// no workflow lists names – targets.json references them as ${NAME}. Explicit environment variables win.
for (const source of ['VARS_JSON', 'SECRETS_JSON']) {
	if (!process.env[source]) continue;
	for (const [name, value] of Object.entries(JSON.parse(process.env[source]))) {
		if (typeof value === 'string' && /^[A-Z][A-Z0-9_]*$/.test(name) && process.env[name] === undefined) process.env[name] = value;
	}
	delete process.env[source];
}

// ── Globs (targets.json include / exclude / protect): ** any depth, * within a segment, ? one character ──────────
const globToRegExp = (glob) => {
	let re = '';
	for (let i = 0; i < glob.length; i++) {
		const c = glob[i];
		if (c === '*' && glob[i + 1] === '*') {
			const slash = glob[i + 2] === '/';
			re += slash ? '(?:.*/)?' : '.*';
			i += slash ? 2 : 1;
		} else if (c === '*') re += '[^/]*';
		else if (c === '?') re += '[^/]';
		else re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
	}
	return new RegExp(`^${re}$`);
};
const matcher = (globs = []) => {
	const res = globs.map(globToRegExp);
	return (path) => res.some((re) => re.test(path));
};

function walk(dir, base = dir, out = []) {
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const full = join(dir, entry.name);
		if (entry.isDirectory()) walk(full, base, out);
		else if (entry.isFile()) out.push(relative(base, full).split(sep).join('/'));
	}
	return out.sort();
}

/** ${VAR} → process.env.VAR; null when a referenced variable is unset or empty */
function expand(value) {
	let missing = false;
	const result = String(value).replace(/\$\{([A-Z0-9_]+)\}/g, (_, name) => {
		const v = process.env[name];
		if (v === undefined || v === '') missing = true;
		return v ?? '';
	});
	return missing ? null : result;
}
const referencesVar = (value) => /\$\{[A-Z0-9_]+\}/.test(String(value));

const phpString = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function generateFile(spec, mask) {
	const lines = ['<?php', `// ${spec.header ?? 'Generated by deploy/deploy.mjs – do not edit on the server.'}`];
	const entries = [];
	for (const [key, raw] of Object.entries(spec.values)) {
		const value = expand(raw);
		if (value === null) continue; // unset → the app's default applies
		entries.push([key, mask && referencesVar(raw) ? '***' : value]);
	}
	if (spec.format === 'php-define') {
		for (const [key, value] of entries) lines.push(`define(${phpString(key)}, ${phpString(value)});`);
	} else if (spec.format === 'php-return') {
		lines.push('return [');
		for (const [key, value] of entries) lines.push(`    ${phpString(key)} => ${phpString(value)},`);
		lines.push('];');
	} else throw new Error(`unknown generate format ${spec.format}`);
	return { text: lines.join('\n') + '\n', keys: entries.map(([k]) => k) };
}

const run = (command, cwd, env = process.env) => {
	console.log(`  $ ${command}   (in ${relative(repoRoot, cwd) || '.'})`);
	execSync(command, { cwd, env, stdio: 'inherit' });
};

function buildEnv(target) {
	const env = { ...process.env };
	for (const entry of target.buildEnv ?? []) {
		const [name, value] = entry.includes('=') ? entry.split(/=(.*)/s) : [entry, `\${${entry}}`];
		const expanded = expand(value);
		if (expanded === null) delete env[name];
		else env[name] = expanded;
	}
	return env;
}

function deployApp(app) {
	const target = config.targets[app];
	const protocol = config.protocols[target.protocol];
	if (!protocol) throw new Error(`${app}: unknown protocol ${target.protocol}`);
	const source = join(repoRoot, target.source);
	const stage = join(repoRoot, '.deploy', app);
	console.log(`\n━━ ${app}: ${target.description}`);

	// 1. build (npm apps in place)
	if (target.build && !target.stageFirst && !skipBuild) run(target.build, repoRoot, buildEnv(target));
	const from = target.stageFirst ? source : join(repoRoot, target.output);
	if (!existsSync(from)) throw new Error(`${app}: ${relative(repoRoot, from)} does not exist – build first (or drop --skip-build)`);

	// 2. stage: include / exclude
	rmSync(stage, { recursive: true, force: true });
	mkdirSync(stage, { recursive: true });
	const include = matcher(target.include ?? ['**']);
	const exclude = matcher(target.exclude ?? []);
	for (const file of walk(from)) {
		if (!include(file) || exclude(file)) continue;
		mkdirSync(join(stage, file, '..'), { recursive: true });
		cpSync(join(from, file), join(stage, file));
	}
	// 1b. build (PHP apps in the staging copy – never touches the dev vendor/)
	if (target.build && target.stageFirst) {
		if (skipBuild) console.log(`  (build skipped: ${target.build})`);
		else run(target.build, stage, buildEnv(target));
	}

	// 3. version.json
	if (target.version) {
		const out = join(stage, target.version, '..');
		const info = writeVersion(source, out, app);
		console.log(`  version.json → ${target.version}: ${info.version} · ${info.git_sha.slice(0, 12)} · shared ${JSON.stringify(info.shared)}`);
	}

	// 4. generated files
	for (const [path, spec] of Object.entries(target.generate ?? {})) {
		const { text, keys } = generateFile(spec, false);
		writeFileSync(join(stage, path), text);
		console.log(`  generated ${path}: ${keys.join(', ') || '(no values – defaults)'}`);
	}

	// 5. plan
	// (files that vanish while listing – e.g. composer's tmp-*.zip on Windows – are not part of the upload)
	const sizes = new Map();
	for (const f of walk(stage)) {
		try {
			sizes.set(f, statSync(join(stage, f)).size);
		} catch {
			/* gone */
		}
	}
	const files = [...sizes.keys()];
	const bytes = [...sizes.values()].reduce((sum, n) => sum + n, 0);
	const url = `${target.protocol}://$${protocol.credentials?.server ?? 'HOST'}/${target.remote}`;
	console.log(`  ${dryRun ? 'would upload' : 'uploads'} ${files.length} files (${(bytes / 1024).toFixed(0)} KiB) from .deploy/${app}/ → ${url}`);
	if (list === 'all') for (const f of files) console.log(`    ${target.remote}${f}`);
	else {
		const top = {};
		for (const f of files) {
			const key = f.includes('/') ? f.split('/')[0] + '/' : f;
			top[key] = (top[key] ?? 0) + 1;
		}
		for (const [k, n] of Object.entries(top)) console.log(`    ${target.remote}${k}${n > 1 || k.endsWith('/') ? `  (${n} files)` : ''}`);
	}
	const protect = target.protect ?? [];
	if (protect.length) console.log(`  never touched on the host: ${protect.map((p) => target.remote + p).join(', ')}`);
	if (target.reminder) console.log(`  ⚠ ${target.reminder}`);

	if (github && process.env.GITHUB_OUTPUT) {
		// FTP-Deploy-Action: excluded paths are neither uploaded nor deleted – keep its defaults + protect
		const excludeList = ['**/.git*', '**/.git*/**', '**/node_modules/**', ...protect];
		appendFileSync(process.env.GITHUB_OUTPUT, [
			`protocol=${target.protocol}`,
			`local_dir=./.deploy/${app}/`,
			`server_dir=${target.remote.endsWith('/') ? target.remote : target.remote + '/'}`,
			'exclude<<__EXCLUDE__', ...excludeList, '__EXCLUDE__',
			`reminder=${target.reminder ?? ''}`,
			''
		].join('\n'));
	}
	return { app, files: files.length, bytes };
}

const apps = requested === 'all' ? config.order : [requested];
const summary = [];
for (const app of apps) summary.push(deployApp(app));
if (apps.length > 1) {
	console.log('\nSummary');
	for (const s of summary) console.log(`  ${s.app.padEnd(8)} ${String(s.files).padStart(6)} files ${(s.bytes / 1024).toFixed(0).padStart(8)} KiB → ${config.targets[s.app].remote}`);
}
